// Helper to generate realistic historical K-line bars
function generateHistory(basePrice: number, points = 24): Array<{ time: string; open: number; high: number; low: number; close: number; volume: number }> {
  const history = [];
  let price = basePrice * 0.88;
  const hours = ['09:30', '10:00', '10:30', '11:00', '11:30', '13:00', '13:30', '14:00', '14:30', '15:00'];
  
  for (let i = 0; i < points; i++) {
    const shift = (Math.random() - 0.48) * (price * 0.035);
    const open = Math.round(price * 100) / 100;
    const close = Math.round((open + shift) * 100) / 100;
    const high = Math.round((Math.max(open, close) + Math.random() * (price * 0.015)) * 100) / 100;
    const low = Math.round((Math.min(open, close) - Math.random() * (price * 0.015)) * 100) / 100;
    const volume = Math.floor(500 + Math.random() * 4500) * 10;
    
    const timeLabel = `T-${points - i}h`;
    history.push({
      time: timeLabel,
      open,
      high,
      low,
      close,
      volume,
    });
    price = close;
  }
  return history;
}

